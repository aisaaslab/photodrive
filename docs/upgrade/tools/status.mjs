#!/usr/bin/env node
// Progress tool for the upgrade plan. No dependencies.
//
//   node docs/upgrade/tools/status.mjs            refresh the status table in README.md
//   node docs/upgrade/tools/status.mjs print      print the status table, change nothing
//   node docs/upgrade/tools/status.mjs next [n]   list the next n open tasks (default 5)
//   node docs/upgrade/tools/status.mjs start S1-03    mark a task in progress   [~]
//   node docs/upgrade/tools/status.mjs done  S1-03    mark a task done          [x]
//   node docs/upgrade/tools/status.mjs reopen S1-03   mark a task not started   [ ]
//
// Task lines look like:  - [ ] **S1-03** · L · Title…
// The README table sits between <!-- STATUS:START --> and <!-- STATUS:END -->.

import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SPRINT_DIR = join(ROOT, "sprints");
const README = join(ROOT, "README.md");
const TASK_RE = /^- \[([ x~])\] \*\*(S\d+-\d+)\*\* · ([SML]) · (.*)$/;
const DAYS = { S: 0.5, M: 1.5, L: 3 };

export function parseSprint(text, file) {
  const lines = text.split("\n");
  const title = (lines.find((l) => l.startsWith("# ")) ?? `# ${file}`).slice(2).trim();
  const field = (name) => {
    const m = text.match(new RegExp(`^\\*\\*${name}:\\*\\*\\s*(.+)$`, "m"));
    return m ? m[1].trim() : "";
  };
  const tasks = [];
  lines.forEach((line, i) => {
    const m = line.match(TASK_RE);
    if (m) tasks.push({ mark: m[1], id: m[2], size: m[3], title: m[4].trim(), line: i });
  });
  return { file, title, phase: field("Phase"), goal: field("Goal"), tasks };
}

export function loadSprints() {
  return readdirSync(SPRINT_DIR)
    .filter((f) => /^S\d+.*\.md$/.test(f))
    .sort()
    .map((f) => parseSprint(readFileSync(join(SPRINT_DIR, f), "utf8"), f));
}

function sprintStatus(s) {
  const done = s.tasks.filter((t) => t.mark === "x").length;
  const active = s.tasks.some((t) => t.mark === "~");
  if (s.tasks.length > 0 && done === s.tasks.length) return "Done";
  if (done > 0 || active) return "In progress";
  return "Not started";
}

export function renderTable(sprints) {
  const rows = [];
  let totalDone = 0, totalAll = 0, daysAll = 0, daysDone = 0;
  for (const s of sprints) {
    const done = s.tasks.filter((t) => t.mark === "x").length;
    const days = s.tasks.reduce((a, t) => a + DAYS[t.size], 0);
    const dDone = s.tasks.filter((t) => t.mark === "x").reduce((a, t) => a + DAYS[t.size], 0);
    totalDone += done; totalAll += s.tasks.length; daysAll += days; daysDone += dDone;
    const [id, ...rest] = s.title.split(" — ");
    const link = `[${id}](sprints/${s.file})`;
    rows.push(`| ${link} | ${rest.join(" — ")} | ${s.phase.replace(/^\d+ · /, "")} | ${done}/${s.tasks.length} | ~${days} d | ${sprintStatus(s)} |`);
  }
  const pct = totalAll ? Math.round((totalDone / totalAll) * 100) : 0;
  const focus = sprints.find((s) => sprintStatus(s) !== "Done");
  const next = focus ? focus.tasks.filter((t) => t.mark !== "x").slice(0, 3).map((t) => `${t.id}`).join(", ") : "none";
  return [
    `**Overall: ${totalDone}/${totalAll} tasks (${pct} %)** · est. ${daysDone}/${daysAll} ideal dev-days · current focus: ${focus ? focus.title.split(" — ")[0] : "complete"} · next up: ${next}`,
    "",
    "| Sprint | Goal | Phase | Tasks | Est. effort | Status |",
    "|---|---|---|---|---|---|",
    ...rows,
  ].join("\n");
}

function writeReadme(table) {
  const text = readFileSync(README, "utf8");
  const start = "<!-- STATUS:START -->";
  const end = "<!-- STATUS:END -->";
  const a = text.indexOf(start), b = text.indexOf(end);
  if (a === -1 || b === -1) throw new Error("README.md is missing the STATUS markers");
  const stamp = new Date().toISOString().slice(0, 10);
  const out = `${text.slice(0, a + start.length)}\n${table}\n\n_Generated by \`tools/status.mjs\` on ${stamp}. Edit the sprint files, not this table._\n${text.slice(b)}`;
  writeFileSync(README, out);
}

function setMark(id, mark) {
  const sprint = loadSprints().find((s) => s.tasks.some((t) => t.id === id));
  if (!sprint) throw new Error(`Unknown task id: ${id}`);
  const path = join(SPRINT_DIR, sprint.file);
  const lines = readFileSync(path, "utf8").split("\n");
  const task = sprint.tasks.find((t) => t.id === id);
  lines[task.line] = lines[task.line].replace(/^- \[[ x~]\]/, `- [${mark}]`);
  writeFileSync(path, lines.join("\n"));
  return task;
}

const [cmd, arg] = process.argv.slice(2);
if (import.meta.url === `file://${process.argv[1]}`) {
  try {
    if (cmd === "print") {
      console.log(renderTable(loadSprints()));
    } else if (cmd === "next") {
      const n = Number(arg) || 5;
      const open = loadSprints().flatMap((s) => s.tasks).filter((t) => t.mark !== "x");
      const ordered = [...open.filter((t) => t.mark === "~"), ...open.filter((t) => t.mark === " ")].slice(0, n);
      for (const t of ordered) console.log(`[${t.mark}] ${t.id} · ${t.size} · ${t.title}`);
      if (ordered.length === 0) console.log("All tasks are done.");
    } else if (cmd === "start" || cmd === "done" || cmd === "reopen") {
      if (!arg) throw new Error(`Usage: status.mjs ${cmd} <task-id>`);
      const t = setMark(arg, { start: "~", done: "x", reopen: " " }[cmd]);
      writeReadme(renderTable(loadSprints()));
      console.log(`${t.id} → ${cmd}`);
    } else if (cmd === undefined || cmd === "update") {
      writeReadme(renderTable(loadSprints()));
      console.log("README.md status table refreshed.");
    } else {
      throw new Error(`Unknown command: ${cmd}`);
    }
  } catch (e) {
    console.error(e.message);
    process.exit(1);
  }
}
