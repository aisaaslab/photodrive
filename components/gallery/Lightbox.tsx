"use client";

import { useEffect, useCallback, useRef, useState } from "react";
import { DriveFile } from "@/lib/drive/types";
import { photoDownloadHref, photoImageSrc, isProtectedPhoto } from "@/lib/drive/photo-src";
import { useLanguage } from "@/lib/i18n";
import { proxyUrl } from "@/lib/drive/proxy-url";

interface Props {
  galleryId: string;
  photos: DriveFile[];
  activeIndex: number;
  favorites: Set<string>;
  allowDownload?: boolean;
  onClose: () => void;
  onNext: () => void;
  onPrev: () => void;
  /** Jump straight to a photo (used by the thumbnail strip). */
  onGoTo: (index: number) => void;
  onToggleFavorite: (photoId: string) => void;
}

export function Lightbox({ galleryId, photos, activeIndex, favorites, allowDownload = true, onClose, onNext, onPrev, onGoTo, onToggleFavorite }: Props) {
  const { t } = useLanguage();
  const g = t.gallery;
  const photo = photos[activeIndex];
  const thumbsRef = useRef<HTMLDivElement>(null);
  const containerRef = useRef<HTMLDivElement>(null);
  const [isFullscreen, setIsFullscreen] = useState(false);
  // Track image load so we show a spinner instead of a black screen while the
  // full-size preview is still being fetched/generated by Drive.
  const [imgLoaded, setImgLoaded] = useState(false);
  // Slideshow: auto-advances every 4s. Spacebar toggles it; it auto-stops at
  // the last photo so a gallery doesn't loop forever in a forgotten tab.
  const [playing, setPlaying] = useState(false);
  const slideRef = useRef<ReturnType<typeof setInterval> | null>(null);
  // ── Zoom + gestures ────────────────────────────────────────────────────
  // Pinch (two fingers), double-tap / double-click, Ctrl/⌘ + wheel, the
  // top-bar button, and the + / − / 0 keys all drive one zoom state: scale `s`
  // plus a pan offset (x, y) in px. It's keyed by photo id, so moving to
  // another photo starts at 1× without an effect.
  // When not zoomed, a one-finger swipe navigates: left/right = prev/next,
  // down = close. When zoomed, one finger (or the mouse) pans instead.
  const MAX_ZOOM = 4;
  const DOUBLE_TAP_ZOOM = 2.5;
  type Zoom = { id: string; s: number; x: number; y: number };
  const pid = photo?.id ?? "";
  const isVideo = !!photo?.mimeType.startsWith("video/");
  const [zoomState, setZoomState] = useState<Zoom>({ id: "", s: 1, x: 0, y: 0 });
  const zoom: Zoom = zoomState.id === pid ? zoomState : { id: pid, s: 1, x: 0, y: 0 };
  const zoomRef = useRef(zoom);
  const imgRef = useRef<HTMLImageElement>(null);
  const areaRef = useRef<HTMLDivElement>(null);
  const pointers = useRef(new Map<number, { x: number; y: number }>());
  const gesture = useRef<{
    kind: "swipe" | "pan" | "pinch";
    sx: number; sy: number;
    startPan: { x: number; y: number };
    startDist: number; startScale: number;
    moved: boolean;
  } | null>(null);
  const lastTap = useRef<{ t: number; x: number; y: number } | null>(null);
  const suppressClick = useRef(false);
  const [gesturing, setGesturing] = useState(false);

  // Dialog focus management: move focus into the viewer, give it back on close.
  useEffect(() => {
    const prev = document.activeElement as HTMLElement | null;
    containerRef.current?.focus({ preventScroll: true });
    return () => prev?.focus?.({ preventScroll: true });
  }, []);

  function setZoomTo(next: { s: number; x: number; y: number }) {
    const v = { id: pid, ...next };
    zoomRef.current = v;
    setZoomState(v);
  }

  // Keep the pan inside the zoomed image's bounds (a little slack isn't needed:
  // the image can't be dragged past its own edges).
  function clampPan(s: number, x: number, y: number) {
    const img = imgRef.current;
    const mx = ((s - 1) * (img?.offsetWidth ?? 0)) / 2;
    const my = ((s - 1) * (img?.offsetHeight ?? 0)) / 2;
    return { x: Math.min(mx, Math.max(-mx, x)), y: Math.min(my, Math.max(-my, y)) };
  }

  function zoomStep(factor: number) {
    const z = zoomRef.current;
    const s = Math.min(MAX_ZOOM, Math.max(1, z.s * factor));
    setZoomTo(s <= 1.02 ? { s: 1, x: 0, y: 0 } : { s, ...clampPan(s, z.x, z.y) });
  }

  function toggleZoom() {
    setZoomTo(zoomRef.current.s > 1 ? { s: 1, x: 0, y: 0 } : { s: DOUBLE_TAP_ZOOM, x: 0, y: 0 });
  }

  // Latest-closure refs for the document-level key / wheel listeners below.
  const zoomStepRef = useRef(zoomStep);
  const isVideoRef = useRef(isVideo);
  useEffect(() => {
    zoomRef.current = zoom;
    zoomStepRef.current = zoomStep;
    isVideoRef.current = isVideo;
  });

  // Ctrl/⌘ + wheel (also what a trackpad pinch emits) zooms. Native listener
  // because React's onWheel is passive and can't preventDefault the page zoom.
  useEffect(() => {
    const el = areaRef.current;
    if (!el) return;
    function onWheel(e: WheelEvent) {
      if (!(e.ctrlKey || e.metaKey) || isVideoRef.current) return;
      e.preventDefault();
      zoomStepRef.current(Math.exp(-e.deltaY * 0.01));
    }
    el.addEventListener("wheel", onWheel, { passive: false });
    return () => el.removeEventListener("wheel", onWheel);
  }, []);

  function onPointerDown(e: React.PointerEvent) {
    if (isVideo) return;
    pointers.current.set(e.pointerId, { x: e.clientX, y: e.clientY });
    const z = zoomRef.current;
    if (pointers.current.size === 2) {
      const [a, b] = [...pointers.current.values()];
      gesture.current = {
        kind: "pinch", sx: 0, sy: 0, startPan: { x: z.x, y: z.y },
        startDist: Math.hypot(a.x - b.x, a.y - b.y) || 1, startScale: z.s, moved: true,
      };
      setGesturing(true);
    } else if (pointers.current.size === 1) {
      gesture.current = {
        kind: z.s > 1 ? "pan" : "swipe", sx: e.clientX, sy: e.clientY,
        startPan: { x: z.x, y: z.y }, startDist: 0, startScale: z.s, moved: false,
      };
      if (z.s > 1) setGesturing(true);
    }
  }

  function onPointerMove(e: React.PointerEvent) {
    const g0 = gesture.current;
    if (!g0 || !pointers.current.has(e.pointerId)) return;
    pointers.current.set(e.pointerId, { x: e.clientX, y: e.clientY });
    if (g0.kind === "pinch" && pointers.current.size >= 2) {
      const [a, b] = [...pointers.current.values()];
      const s = Math.min(MAX_ZOOM, Math.max(1, (g0.startScale * Math.hypot(a.x - b.x, a.y - b.y)) / g0.startDist));
      setZoomTo(s <= 1 ? { s: 1, x: 0, y: 0 } : { s, ...clampPan(s, g0.startPan.x, g0.startPan.y) });
      return;
    }
    const dx = e.clientX - g0.sx;
    const dy = e.clientY - g0.sy;
    if (Math.hypot(dx, dy) > 8) g0.moved = true;
    if (g0.kind === "pan") {
      const s = zoomRef.current.s;
      setZoomTo({ s, ...clampPan(s, g0.startPan.x + dx, g0.startPan.y + dy) });
    }
  }

  function onPointerUp(e: React.PointerEvent) {
    const g0 = gesture.current;
    if (!pointers.current.delete(e.pointerId) || !g0) return;

    // A drag/pinch must not also count as a backdrop click (which would close).
    if (g0.moved) {
      suppressClick.current = true;
      setTimeout(() => { suppressClick.current = false; }, 60);
    }

    if (g0.kind === "pinch") {
      if (pointers.current.size === 0) {
        gesture.current = null;
        setGesturing(false);
        if (zoomRef.current.s < 1.05) setZoomTo({ s: 1, x: 0, y: 0 });
      } else {
        // One finger still down: carry on as a pan from where it is.
        const [p] = [...pointers.current.values()];
        const z = zoomRef.current;
        gesture.current = { kind: "pan", sx: p.x, sy: p.y, startPan: { x: z.x, y: z.y }, startDist: 0, startScale: z.s, moved: true };
      }
      return;
    }

    gesture.current = null;
    setGesturing(false);
    const dx = e.clientX - g0.sx;
    const dy = e.clientY - g0.sy;

    // Swipe navigation (touch / pen, only while not zoomed).
    if (g0.kind === "swipe" && e.pointerType !== "mouse") {
      if (Math.abs(dx) > 50 && Math.abs(dx) > Math.abs(dy) * 1.5) {
        if (dx < 0) onNext();
        else onPrev();
        return;
      }
      if (dy > 90 && dy > Math.abs(dx) * 1.5) {
        onClose();
        return;
      }
    }

    // Double-tap / double-click on the photo toggles zoom.
    if (!g0.moved && (e.target as HTMLElement).tagName === "IMG") {
      const now = Date.now();
      const lt = lastTap.current;
      if (lt && now - lt.t < 300 && Math.hypot(e.clientX - lt.x, e.clientY - lt.y) < 30) {
        lastTap.current = null;
        toggleZoom();
      } else {
        lastTap.current = { t: now, x: e.clientX, y: e.clientY };
      }
    }
  }

  function onPointerCancel(e: React.PointerEvent) {
    pointers.current.delete(e.pointerId);
    if (pointers.current.size === 0) {
      gesture.current = null;
      setGesturing(false);
    }
  }

  useEffect(() => {
    setImgLoaded(false);
  }, [activeIndex]);

  // Slideshow interval — started/stopped by the `playing` state. When playing
  // reaches the last photo, it auto-stops. The interval is cleared on any
  // manual navigation (activeIndex changes) and re-created so the 4s timer
  // resets after each advance, giving each photo a full 4 seconds.
  useEffect(() => {
    if (!playing) {
      if (slideRef.current) clearInterval(slideRef.current);
      return;
    }
    if (activeIndex >= photos.length - 1) {
      // Reached the end while playing — stop, don't loop.
      setPlaying(false);
      return;
    }
    slideRef.current = setInterval(() => {
      onNext();
    }, 4000);
    return () => {
      if (slideRef.current) clearInterval(slideRef.current);
    };
  }, [playing, activeIndex, photos.length, onNext]);

  // Preload the next and previous full-size images so navigating feels instant
  // (the browser caches them in the background while you view the current one).
  useEffect(() => {
    for (const i of [activeIndex + 1, activeIndex - 1]) {
      const p = photos[i];
      if (p && !p.mimeType.startsWith("video/")) {
        const img = new window.Image();
        img.src = photoImageSrc(p, 2048);
      }
    }
  }, [activeIndex, photos]);

  function toggleFullscreen() {
    if (!document.fullscreenElement) {
      containerRef.current?.requestFullscreen();
    } else {
      document.exitFullscreen();
    }
  }

  useEffect(() => {
    const handler = () => setIsFullscreen(!!document.fullscreenElement);
    document.addEventListener("fullscreenchange", handler);
    return () => document.removeEventListener("fullscreenchange", handler);
  }, []);

  const handleKey = useCallback(
    (e: KeyboardEvent) => {
      if (e.key === "Escape" && !document.fullscreenElement) onClose();
      if (e.key === "ArrowRight") onNext();
      if (e.key === "ArrowLeft") onPrev();
      if (e.key === "f" || e.key === "F") toggleFullscreen();
      if (!isVideoRef.current) {
        if (e.key === "+" || e.key === "=") zoomStepRef.current(1.5);
        if (e.key === "-" || e.key === "_") zoomStepRef.current(1 / 1.5);
        if (e.key === "0") zoomStepRef.current(1 / MAX_ZOOM);
      }
      // Spacebar toggles the slideshow. preventDefault stops the page from
      // scrolling (the lightbox already locks body overflow, but a button might
      // be focused and would otherwise get a click on space).
      if (e.key === " ") {
        e.preventDefault();
        setPlaying((v) => !v);
      }
    },
    [onClose, onNext, onPrev]
  );

  useEffect(() => {
    document.addEventListener("keydown", handleKey);
    document.body.style.overflow = "hidden";
    return () => {
      document.removeEventListener("keydown", handleKey);
      document.body.style.overflow = "";
    };
  }, [handleKey]);

  // Scroll active thumbnail into view
  useEffect(() => {
    if (thumbsRef.current) {
      const active = thumbsRef.current.querySelector("[data-active='true']") as HTMLElement;
      active?.scrollIntoView({ behavior: "smooth", block: "nearest", inline: "center" });
    }
  }, [activeIndex]);

  if (!photo) return null;

  const isFavorited = favorites.has(photo.id);

  return (
    <div
      ref={containerRef}
      role="dialog"
      aria-modal="true"
      aria-label={g.viewerLabel}
      tabIndex={-1}
      className="fixed inset-0 z-50 bg-black/98 flex flex-col animate-fade-in outline-none"
    >
      {/* Top bar */}
      <div className="flex items-center justify-between px-5 py-4 shrink-0">
        {/* Counter */}
        <span className="text-white/50 text-sm">
          {activeIndex + 1} <span className="text-white/25">/</span> {photos.length}
        </span>

        {/* Actions */}
        <div className="flex items-center gap-2">
          {/* Slideshow play/pause */}
          <button
            onClick={() => setPlaying((v) => !v)}
            title={g.slideshow}
            aria-pressed={playing}
            className={`flex items-center gap-1.5 rounded-full px-3 py-1.5 text-xs font-medium transition-all ${
              playing
                ? "bg-[#17509e] text-white"
                : "bg-white/10 text-white/70 hover:bg-white/20"
            }`}
          >
            {playing ? (
              <svg className="w-3.5 h-3.5" fill="currentColor" viewBox="0 0 24 24">
                <path d="M6 5h4v14H6zM14 5h4v14h-4z" />
              </svg>
            ) : (
              <svg className="w-3.5 h-3.5" fill="currentColor" viewBox="0 0 24 24">
                <path d="M8 5.14v14l11-7-11-7z" />
              </svg>
            )}
            {g.slideshow}
          </button>

          {/* Favorite */}
          <button
            onClick={() => onToggleFavorite(photo.id)}
            aria-pressed={isFavorited}
            className={`flex items-center gap-1.5 rounded-full px-3 py-1.5 text-xs font-medium transition-all ${
              isFavorited
                ? "bg-[#17509e] text-white"
                : "bg-white/10 text-white/70 hover:bg-white/20"
            }`}
          >
            <svg className="w-3.5 h-3.5" viewBox="0 0 24 24" fill={isFavorited ? "currentColor" : "none"} stroke="currentColor" strokeWidth={2}>
              <path strokeLinecap="round" strokeLinejoin="round" d="M21 8.25c0-2.485-2.099-4.5-4.688-4.5-1.935 0-3.597 1.126-4.312 2.733-.715-1.607-2.377-2.733-4.313-2.733C5.1 3.75 3 5.765 3 8.25c0 7.22 9 12 9 12s9-4.78 9-12z" />
            </svg>
            {g.favorite}
          </button>

          {/* Download */}
          {allowDownload && photoDownloadHref(photo) && (
            <a
              href={photoDownloadHref(photo)!}
              download={photo.name}
              onClick={(e) => e.stopPropagation()}
              className="flex items-center gap-1.5 bg-white/10 hover:bg-white/20 text-white/70 hover:text-white rounded-full px-3 py-1.5 text-xs font-medium transition-all"
            >
              <svg className="w-3.5 h-3.5" fill="none" viewBox="0 0 24 24" stroke="currentColor" strokeWidth={2}>
                <path strokeLinecap="round" strokeLinejoin="round" d="M3 16.5v2.25A2.25 2.25 0 005.25 21h13.5A2.25 2.25 0 0021 18.75V16.5M16.5 12L12 16.5m0 0L7.5 12m4.5 4.5V3" />
              </svg>
              {g.download}
            </a>
          )}

          {/* Zoom (photos only): toggles 1× ↔ 2.5×. Pinch, double-tap and
              + / − / 0 work too. */}
          {!isVideo && (
            <button
              onClick={toggleZoom}
              title={`${g.zoom} (+ / − / 0)`}
              aria-label={g.zoom}
              aria-pressed={zoom.s > 1}
              className={`w-8 h-8 flex items-center justify-center rounded-full transition-all ${
                zoom.s > 1 ? "bg-[#17509e] text-white" : "bg-white/10 hover:bg-white/20 text-white/70 hover:text-white"
              }`}
            >
              <svg className="w-4 h-4" fill="none" viewBox="0 0 24 24" stroke="currentColor" strokeWidth={2}>
                <path strokeLinecap="round" strokeLinejoin="round" d="M21 21l-5.197-5.197m0 0A7.5 7.5 0 105.196 5.196a7.5 7.5 0 0010.607 10.607zM10.5 7.5v6m3-3h-6" />
              </svg>
            </button>
          )}

          {/* Fullscreen */}
          <button
            onClick={toggleFullscreen}
            title={g.fullscreen}
            aria-label={g.fullscreen}
            className="w-8 h-8 flex items-center justify-center bg-white/10 hover:bg-white/20 text-white/70 hover:text-white rounded-full transition-all"
          >
            {isFullscreen ? (
              <svg className="w-4 h-4" fill="none" viewBox="0 0 24 24" stroke="currentColor" strokeWidth={2}>
                <path strokeLinecap="round" strokeLinejoin="round" d="M9 9V4.5M9 9H4.5M9 9L3.75 3.75M9 15v4.5M9 15H4.5M9 15l-5.25 5.25M15 9h4.5M15 9V4.5M15 9l5.25-5.25M15 15h4.5M15 15v4.5m0-4.5l5.25 5.25" />
              </svg>
            ) : (
              <svg className="w-4 h-4" fill="none" viewBox="0 0 24 24" stroke="currentColor" strokeWidth={2}>
                <path strokeLinecap="round" strokeLinejoin="round" d="M3.75 3.75v4.5m0-4.5h4.5m-4.5 0L9 9M3.75 20.25v-4.5m0 4.5h4.5m-4.5 0L9 15M20.25 3.75h-4.5m4.5 0v4.5m0-4.5L15 9m5.25 11.25h-4.5m4.5 0v-4.5m0 4.5L15 15" />
              </svg>
            )}
          </button>

          {/* Close */}
          <button
            onClick={onClose}
            aria-label={g.closeViewer}
            title={g.closeViewer}
            className="w-8 h-8 flex items-center justify-center bg-white/10 hover:bg-white/20 text-white/70 hover:text-white rounded-full transition-all"
          >
            <svg className="w-4 h-4" fill="none" viewBox="0 0 24 24" stroke="currentColor" strokeWidth={2}>
              <path strokeLinecap="round" strokeLinejoin="round" d="M6 18L18 6M6 6l12 12" />
            </svg>
          </button>
        </div>
      </div>

      {/* Main image area */}
      <div
        ref={areaRef}
        className="flex-1 flex items-center justify-center relative px-2 sm:px-14 min-h-0 touch-none"
        onClick={() => { if (!suppressClick.current) onClose(); }}
        onPointerDown={onPointerDown}
        onPointerMove={onPointerMove}
        onPointerUp={onPointerUp}
        onPointerCancel={onPointerCancel}
      >
        {/* Prev */}
        {activeIndex > 0 && (
          <button
            className="absolute left-3 top-1/2 -translate-y-1/2 w-10 h-10 flex items-center justify-center bg-white/10 hover:bg-white/20 text-white rounded-full transition-all z-10 hover:scale-110"
            onClick={(e) => { e.stopPropagation(); onPrev(); }}
            aria-label={g.prevPhoto}
          >
            <svg className="w-5 h-5" fill="none" viewBox="0 0 24 24" stroke="currentColor" strokeWidth={2}>
              <path strokeLinecap="round" strokeLinejoin="round" d="M15.75 19.5L8.25 12l7.5-7.5" />
            </svg>
          </button>
        )}

        {/* Image or Video */}
        <div onClick={(e) => e.stopPropagation()} className="max-w-5xl max-h-full w-full flex items-center justify-center relative">
          {photo.mimeType.startsWith("video/") ? (
            photo.urls ? (
              // Protected gallery: the signed same-site stream, so no Drive id or URL reaches the browser.
              <video
                key={photo.id}
                src={photo.urls.stream}
                controls
                playsInline
                controlsList={allowDownload ? undefined : "nodownload"}
                className="w-full max-w-4xl aspect-video max-h-[75vh] rounded-lg shadow-2xl animate-scale-in bg-black"
              />
            ) : (
              // Play the video straight from Google Drive's own player (no bytes
              // through our server). Keeps video off Vercel bandwidth.
              <iframe
                key={photo.id}
                src={`https://drive.google.com/file/d/${photo.id}/preview`}
                allow="autoplay; fullscreen"
                allowFullScreen
                className="w-full max-w-4xl aspect-video max-h-[75vh] rounded-lg shadow-2xl animate-scale-in border-0"
              />
            )
          ) : (
            <>
              {!imgLoaded && (
                <div className="absolute inset-0 flex items-center justify-center pointer-events-none">
                  <div className="w-8 h-8 border-2 border-white/20 border-t-white/80 rounded-full animate-spin" />
                </div>
              )}
              {/* The wrapper owns the entrance animation: an animation with
                  fill-mode `both` would otherwise override the zoom transform. */}
              <div key={photo.id} className="max-w-full animate-scale-in">
              {/* eslint-disable-next-line @next/next/no-img-element */}
              <img
                ref={imgRef}
                draggable={false}
                src={photoImageSrc(photo, 2048)}
                alt={photo.name}
                fetchPriority="high"
                decoding="async"
                onLoad={() => setImgLoaded(true)}
                onError={(e) => {
                  const img = e.currentTarget;
                  if (!img.dataset.fallback && !isProtectedPhoto(photo)) {
                    img.dataset.fallback = "1";
                    img.src = proxyUrl(galleryId, photo.id, "preview");
                  } else {
                    setImgLoaded(true);
                  }
                }}
                style={{
                  transform: `translate(${zoom.x}px, ${zoom.y}px) scale(${zoom.s})`,
                  transition: gesturing ? "none" : "transform 0.2s ease, opacity 0.3s",
                  cursor: zoom.s > 1 ? (gesturing ? "grabbing" : "grab") : "zoom-in",
                }}
                className={`block max-w-full max-h-[75vh] object-contain rounded-lg shadow-2xl select-none ${imgLoaded ? "opacity-100" : "opacity-0"}`}
              />
              </div>
            </>
          )}
        </div>

        {/* Next */}
        {activeIndex < photos.length - 1 && (
          <button
            className="absolute right-3 top-1/2 -translate-y-1/2 w-10 h-10 flex items-center justify-center bg-white/10 hover:bg-white/20 text-white rounded-full transition-all z-10 hover:scale-110"
            onClick={(e) => { e.stopPropagation(); onNext(); }}
            aria-label={g.nextPhoto}
          >
            <svg className="w-5 h-5" fill="none" viewBox="0 0 24 24" stroke="currentColor" strokeWidth={2}>
              <path strokeLinecap="round" strokeLinejoin="round" d="M8.25 4.5l7.5 7.5-7.5 7.5" />
            </svg>
          </button>
        )}
      </div>

      {/* Thumbnail strip */}
      <div className="shrink-0 pb-4 pt-3">
        <div
          ref={thumbsRef}
          className="flex gap-1.5 overflow-x-auto px-4 pb-1"
          style={{ scrollbarWidth: "none" }}
        >
          {photos.map((p, i) => (
            <button
              key={p.id}
              data-active={i === activeIndex ? "true" : "false"}
              onClick={() => onGoTo(i)}
              aria-label={`${i + 1} / ${photos.length}`}
              aria-current={i === activeIndex ? "true" : undefined}
              className={`relative shrink-0 w-14 h-14 rounded-lg overflow-hidden transition-all ${
                i === activeIndex
                  ? "ring-2 ring-white opacity-100 scale-105"
                  : "opacity-40 hover:opacity-70"
              }`}
            >
              {/* eslint-disable-next-line @next/next/no-img-element */}
              <img
                src={photoImageSrc(p, 150)}
                alt=""
                loading="lazy"
                onError={(e) => {
                  // If Google's CDN throttles/fails, fall back to our proxy once.
                  const img = e.currentTarget;
                  if (!img.dataset.fallback && !isProtectedPhoto(p)) {
                    img.dataset.fallback = "1";
                    img.src = proxyUrl(galleryId, p.id, "thumb");
                  }
                }}
                className="w-full h-full object-cover"
              />
              {favorites.has(p.id) && (
                <div className="absolute top-0.5 right-0.5 w-3 h-3 bg-[#17509e] rounded-full" />
              )}
            </button>
          ))}
        </div>
      </div>
    </div>
  );
}
