"use client";

import { useEffect, useState } from "react";
import { DriveFile } from "@/lib/drive/types";
import { photoDownloadHref, photoImageSrc } from "@/lib/drive/photo-src";
import { useLanguage } from "@/lib/i18n";
import { LightboxTopBar } from "./LightboxTopBar";
import { LightboxStage } from "./LightboxStage";
import { LightboxThumbnails } from "./LightboxThumbnails";
import { useLightboxZoom } from "./useLightboxZoom";
import { useSlideshow } from "./useSlideshow";
import { useLightboxFrame } from "./useLightboxFrame";

interface Props {
  galleryId: string;
  photos: DriveFile[];
  activeIndex: number;
  favorites: Set<string>;
  allowDownload?: boolean;
  onClose: () => void;
  onNext: () => void;
  onPrev: () => void;
  /** Jump straight to a photo (used by the thumbnail strip). */
  onGoTo: (index: number) => void;
  onToggleFavorite: (photoId: string) => void;
}

/**
 * The full-screen photo viewer. The pieces live next to it (S5-10): zoom and gestures (useLightboxZoom, with the rules in
 * lib/gallery/lightbox-math.ts), the slideshow, window behaviour (focus, fullscreen, keys), and the top bar, stage and thumbnail
 * strip as components. This file holds what they share and puts them together.
 */
export function Lightbox({ galleryId, photos, activeIndex, favorites, allowDownload = true, onClose, onNext, onPrev, onGoTo, onToggleFavorite }: Props) {
  const { t } = useLanguage();
  const g = t.gallery;
  const photo = photos[activeIndex];
  // Track image load so we show a spinner instead of a black screen while the
  // full-size preview is still being fetched/generated by Drive.
  const [imgLoaded, setImgLoaded] = useState(false);
  const isVideo = !!photo?.mimeType.startsWith("video/");

  const zoomCtl = useLightboxZoom({ pid: photo?.id ?? "", isVideo, onNext, onPrev, onClose });
  const { playing, toggle: toggleSlideshow } = useSlideshow(activeIndex, photos.length, onNext);
  const { containerRef, isFullscreen, toggleFullscreen } = useLightboxFrame({
    onClose, onNext, onPrev, toggleSlideshow, zoomStepRef: zoomCtl.zoomStepRef, isVideoRef: zoomCtl.isVideoRef,
  });

  useEffect(() => {
    setImgLoaded(false);
  }, [activeIndex]);

  // Preload the next and previous full-size images so navigating feels instant
  // (the browser caches them in the background while you view the current one).
  useEffect(() => {
    for (const i of [activeIndex + 1, activeIndex - 1]) {
      const p = photos[i];
      if (p && !p.mimeType.startsWith("video/")) {
        const img = new window.Image();
        img.src = photoImageSrc(p, 2048);
      }
    }
  }, [activeIndex, photos]);

  if (!photo) return null;

  const href = allowDownload ? photoDownloadHref(photo) : null;

  return (
    <div
      ref={containerRef}
      role="dialog"
      aria-modal="true"
      aria-label={g.viewerLabel}
      tabIndex={-1}
      className="fixed inset-0 z-50 bg-black/98 flex flex-col animate-fade-in outline-none"
    >
      <LightboxTopBar
        index={activeIndex}
        total={photos.length}
        playing={playing}
        onToggleSlideshow={toggleSlideshow}
        isFavorited={favorites.has(photo.id)}
        onToggleFavorite={() => onToggleFavorite(photo.id)}
        download={href ? { href, name: photo.name } : null}
        showZoom={!isVideo}
        zoomed={zoomCtl.zoom.s > 1}
        onToggleZoom={zoomCtl.toggleZoom}
        isFullscreen={isFullscreen}
        onToggleFullscreen={toggleFullscreen}
        onClose={onClose}
      />
      <LightboxStage
        photo={photo}
        galleryId={galleryId}
        activeIndex={activeIndex}
        total={photos.length}
        allowDownload={allowDownload}
        onPrev={onPrev}
        onNext={onNext}
        onClose={onClose}
        imgLoaded={imgLoaded}
        onImgLoaded={() => setImgLoaded(true)}
        zoom={zoomCtl.zoom}
        gesturing={zoomCtl.gesturing}
        areaRef={zoomCtl.areaRef}
        imgRef={zoomCtl.imgRef}
        suppressClick={zoomCtl.suppressClick}
        pointerHandlers={zoomCtl.pointerHandlers}
      />
      <LightboxThumbnails photos={photos} activeIndex={activeIndex} favorites={favorites} galleryId={galleryId} onGoTo={onGoTo} />
    </div>
  );
}
